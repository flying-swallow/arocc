#!/usr/bin/env python3
"""Generate src/c3/identifier_tables.c3 from src/aro/char_info/identifier_tables.zig.

The Zig file is the reference copy of the unicode-ident XID_Start/XID_Continue
trie (Unicode data, see LICENSE-UNICODE). This script copies its data verbatim
so the C3 port uses exactly the same Unicode version, never the host's.

Usage (from the repository root):
    python3 tools/gen_identifier_tables.py           # rewrite the C3 file
    python3 tools/gen_identifier_tables.py --check   # exit 1 if it is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src/aro/char_info/identifier_tables.zig"
DST = ROOT / "src/c3/identifier_tables.c3"

ARRAY_RE = re.compile(
    r"pub const (\w+): \[(\d+)\]u8(?: align\(\d+\))? = \.\{(.*?)\};", re.S
)
CHUNK_RE = re.compile(r"pub const chunk = (\d+);")


def generate() -> str:
    text = SRC.read_text()
    header = [line[3:].strip() for line in text.splitlines() if line.startswith("//!")]
    chunk = CHUNK_RE.search(text)
    if not chunk:
        sys.exit("chunk constant not found")
    out = [
        "// GENERATED by tools/gen_identifier_tables.py from",
        "// src/aro/char_info/identifier_tables.zig. Do not edit by hand.",
        "//",
    ]
    out += ["// " + h for h in header]
    out += [
        "// The table data is Unicode data; see LICENSE-UNICODE at the repository root.",
        "module aro::identifier_tables;",
        "",
        f"const uint CHUNK = {chunk.group(1)};",
    ]
    arrays = ARRAY_RE.findall(text)
    if [a[0] for a in arrays] != ["trie_start", "trie_continue", "leaf"]:
        sys.exit(f"unexpected arrays: {[a[0] for a in arrays]}")
    for name, length, body in arrays:
        values = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
        if len(values) != int(length):
            sys.exit(f"{name}: expected {length} values, found {len(values)}")
        for v in values:
            if not re.fullmatch(r"0x[0-9A-Fa-f]{2}", v):
                sys.exit(f"{name}: bad value {v!r}")
        out.append("")
        out.append(f"const char[{length}] {name.upper()} = {{")
        for i in range(0, len(values), 16):
            out.append("\t" + ", ".join(values[i : i + 16]) + ",")
        out.append("};")
    return "\n".join(out) + "\n"


def main() -> int:
    content = generate()
    if "--check" in sys.argv[1:]:
        if not DST.exists() or DST.read_text() != content:
            print(f"{DST.relative_to(ROOT)} is stale; rerun tools/gen_identifier_tables.py")
            return 1
        return 0
    DST.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
